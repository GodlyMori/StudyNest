  static List<QuizQuestion> getQuestionsForSubject(String subject) {
    final normalized = subject.trim().toLowerCase();
    if (normalized.contains('calculus') ||
        normalized.contains('math') ||
        normalized.contains('algebra')) {
      return calculusQuestions;
    } else if (normalized.contains('bio')) {
      return biologyQuestions;
    } else if (normalized.contains('hist') ||
        normalized.contains('war') ||
        normalized.contains('civilization')) {
      return historyQuestions;
    } else if (normalized.contains('phys') ||
        normalized.contains('newton') ||
        normalized.contains('force') ||
        normalized.contains('chem')) {
      return physicsQuestions;
    }
    // Default fallback to Calculus
    return calculusQuestions;
  }
